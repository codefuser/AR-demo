// ---------------------------------------------------------------------------
// Building State
// ---------------------------------------------------------------------------

/**
 * Building-related state stored in Zustand.
 * Phase 2: Added updateBuilding, deleteBuilding, getBuildingById.
 */
export interface BuildingState {
  /** In-memory list of all buildings. */
  buildings: Building[];
  /** ID of the currently selected / viewed building. */
  selectedBuildingId: string | null;
  /** Whether a loading operation is in progress. */
  isLoading: boolean;
  /** Last error message, if any. */
  error: string | null;

  // ── Read ──────────────────────────────────────────────────────────────────
  /** Replace the full buildings list. */
  setBuildings: (buildings: Building[]) => void;

  // ── Create ────────────────────────────────────────────────────────────────
  /** Append a single building to the list. */
  addBuilding: (building: Building) => void;

  // ── Update ────────────────────────────────────────────────────────────────
  /** Update an existing building by ID. */
  updateBuilding: (id: string, payload: UpdateBuildingPayload) => void;

  // ── Delete ────────────────────────────────────────────────────────────────
  /** Remove a building from the list by ID. */
  deleteBuilding: (id: string) => void;

  // ── Selection ─────────────────────────────────────────────────────────────
  /** Set the currently selected building ID (null to deselect). */
  selectBuilding: (id: string | null) => void;

  // ── Status ────────────────────────────────────────────────────────────────
  setLoading: (value: boolean) => void;
  setError: (message: string | null) => void;
}

