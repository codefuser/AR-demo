// ---------------------------------------------------------------------------

/**
 * Scan status of a building.
 * Drives the status badge displayed on BuildingCard and BuildingDetails.
 */
export type ScanStatus = 'not_started' | 'in_progress' | 'completed';

/**
 * Category / type of the indoor building.
 * Used for filtering and display in future phases.
 */
export type BuildingType =
  | 'college'
  | 'school'
  | 'mall'
  | 'hospital'
  | 'office'
  | 'other';

/**
 * Legacy status kept for Phase 1 compatibility.
 * Use ScanStatus for scan-specific state going forward.
 */
export type BuildingStatus = 'draft' | 'scanned' | 'published';

// ---------------------------------------------------------------------------
// Building — Model
// ---------------------------------------------------------------------------

/**
 * Represents a physical indoor building managed by the application.
 *
 * Phase 2 additions: address, buildingType, scanStatus, thumbnailUri.
 */
export interface Building {
  /** Unique identifier (generated by buildingService). */
  id: string;
  /** Human-readable name of the building. */
  name: string;
  /** Optional description. */
  description?: string;
  /** Physical address of the building. */
  address?: string;
  /** Category of the building. */
  buildingType: BuildingType;
  /** Number of floors. Min 1, max 100. */
  floorCount: number;
  /** Current scan status. */
  scanStatus: ScanStatus;
  /** Legacy status field (kept for Phase 1 compatibility). */
  status: BuildingStatus;
  /** Local URI of the building thumbnail image (Phase 2: placeholder only). */
  thumbnailUri?: string;
  /** ISO 8601 timestamp of creation. */
  createdAt: string;
  /** ISO 8601 timestamp of last update. */
  updatedAt: string;
}

/**
 * Payload for creating a new building.
 */
export interface CreateBuildingPayload {
  name: string;
  description?: string;
  address?: string;
  buildingType: BuildingType;
  floorCount: number;
  thumbnailUri?: string;
}

/**
 * Payload for updating an existing building.
 * All fields are optional — only provided fields will be updated.
 */
export type UpdateBuildingPayload = Partial<Omit<Building, 'id' | 'createdAt'>>;

